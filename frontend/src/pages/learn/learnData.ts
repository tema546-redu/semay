export function getSubjectContent(grade: string, subjectId: string) {
  return CONTENT.find((c) => c.grade === grade && c.subjectId === subjectId)
}

export function getChapter(grade: string, subjectId: string, chapterId: string) {
  const sub = getSubjectContent(grade, subjectId)
  return sub?.chapters.find((ch) => ch.id === chapterId)
}
