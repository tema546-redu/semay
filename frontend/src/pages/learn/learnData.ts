const KEY = "semay_learn_ok"

export function isLearnUnlocked(): boolean {
  try {
    return localStorage.getItem(KEY) === "1"
  } catch {
    return false
  }
}

export function setLearnUnlocked(ok: boolean) {
  try {
    if (ok) localStorage.setItem(KEY, "1")
    else localStorage.removeItem(KEY)
  } catch {
    /* ignore */
  }
}

export type NoteNode = {
  id: string
  title: string
  titleAm?: string
  body: string
  bodyAm?: string
  children?: NoteNode[]
}

export type Question = {
  id: string
  type: "mcq" | "short"
  difficulty: "easy" | "medium" | "hard"
  stem: string
  stemAm?: string
  options?: string[] // mcq only
  optionsAm?: string[]
  answer: string // option index "0"|"1"|"2"|"3" for mcq, or short text
  explanation?: string
  explanationAm?: string
}

export type Chapter = {
  id: string
  number: number
  title: string
  titleAm: string
  notes: NoteNode[]
  questions: Question[]
}

